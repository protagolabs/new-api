func ClaudeErrorWrapper(err error, code string, statusCode int) *dto.ClaudeErrorWithStatusCode {
	text := err.Error()
	lowerText := strings.ToLower(text)
	if !strings.HasPrefix(lowerText, "get file base64 from url") {
		if strings.Contains(lowerText, "post") || strings.Contains(lowerText, "dial") || strings.Contains(lowerText, "http") {
			common.SysLog(fmt.Sprintf("error: %s", text))
			text = "请求上游地址失败"
		}
	}
	claudeError := types.ClaudeError{
		Message: text,
		Type:    "new_api_error",
	}
	return &dto.ClaudeErrorWithStatusCode{
		Error:      claudeError,
		StatusCode: statusCode,
	}
}

func ClaudeErrorWrapperLocal(err error, code string, statusCode int) *dto.ClaudeErrorWithStatusCode {
	claudeErr := ClaudeErrorWrapper(err, code, statusCode)
	claudeErr.LocalError = true
	return claudeErr
}

func RelayErrorHandler(ctx context.Context, resp *http.Response, showBodyWhenFail bool) (newApiErr *types.NewAPIError) {
	// Rewrite vendor quota/usage-limit 400 to 429 on every return path so the
	// default retry logic picks them up. Defer covers all early returns below.
	defer func() {
		UpgradeQuotaErrorTo429(newApiErr)
	}()

	newApiErr = types.InitOpenAIError(types.ErrorCodeBadResponseStatusCode, resp.StatusCode)

	responseBody, err := io.ReadAll(resp.Body)
	if err != nil {
		return
	}
	CloseResponseBodyGracefully(resp)
	var errResponse dto.GeneralErrorResponse
	responseBodyText := string(responseBody)
	responseBodyPreview := common.LocalLogPreview(responseBodyText)
	buildErrWithBody := func(message string) error {
		if message == "" {
			return fmt.Errorf("bad response status code %d, body: %s", resp.StatusCode, responseBodyText)
		}
		return fmt.Errorf("bad response status code %d, message: %s, body: %s", resp.StatusCode, message, responseBodyText)
	}

	err = common.Unmarshal(responseBody, &errResponse)
	if err != nil {
		if showBodyWhenFail {
			newApiErr.Err = buildErrWithBody("")
		} else {
			logger.LogError(ctx, fmt.Sprintf("bad response status code %d, body: %s", resp.StatusCode, responseBodyPreview))
			newApiErr.Err = fmt.Errorf("bad response status code %d", resp.StatusCode)
		}
		return
	}

	if common.GetJsonType(errResponse.Error) == "object" {
		// General format error (OpenAI, Anthropic, Gemini, etc.)
		oaiError := errResponse.TryToOpenAIError()
		if oaiError != nil {
			newApiErr = types.WithOpenAIError(*oaiError, resp.StatusCode)
			if showBodyWhenFail {
				newApiErr.Err = buildErrWithBody(newApiErr.Error())
			}
			return
		}
	}
	newApiErr = types.NewOpenAIError(errors.New(errResponse.ToMessage()), types.ErrorCodeBadResponseStatusCode, resp.StatusCode)
	if showBodyWhenFail {
		newApiErr.Err = buildErrWithBody(newApiErr.Error())
	}
	return
}

// retryableQuotaErrorPatternsOn400 are substrings of upstream 400 error
// messages that semantically represent quota/rate-limit exhaustion (HTTP 429)
// instead of a real client request error. Several vendors (Anthropic, jimi,
// kelly, anyfast relays, etc.) emit these as HTTP 400 even though the next
// retry to a different channel would have a good chance of succeeding.
//
// UpgradeQuotaErrorTo429 rewrites the local status to 429 so that the default
// shouldRetry() logic in controller/relay.go triggers a channel retry. The
// upstream HTTP body is left untouched; only the in-memory NewAPIError is
// modified.
var retryableQuotaErrorPatternsOn400 = []string{
	"specified API usage limits", // Anthropic / jimi-style: "You have reached your specified API usage limits."
	"credit balance is too low",  // Anthropic: account credit exhausted
}

func UpgradeQuotaErrorTo429(newApiErr *types.NewAPIError) {
	if newApiErr == nil || newApiErr.StatusCode != http.StatusBadRequest {
		return
	}
	msg := newApiErr.Error()
	for _, p := range retryableQuotaErrorPatternsOn400 {
		if strings.Contains(msg, p) {
			newApiErr.StatusCode = http.StatusTooManyRequests
			return
		}
	}
}

// upstreamForcedRetrySignatures are upstream error messages that should bypass
// our local channel-affinity SkipRetryOnFailure guard and force a retry to
// another channel. These represent upstream-side stale-state failures the
// client cannot do anything about, but a sibling channel could serve.
var upstreamForcedRetrySignatures = []string{
	// Upstream newapi (nested) returned 403 because its own affinity cache
	// is stuck on a channel that has since been disabled.
	// Without bypass, our SkipRetryOnFailure=true would propagate this 403
	// to the client even though our other channels are healthy.
	"channel selected by channel affinity has been disabled",
	// Nested upstream returned this 403 for a disabled affinity-pinned channel.
	"This channel has been disabled",
	// Bedrock ValidationException for anthropic-beta flags it doesn't recognize
	// (client sent prompt-caching-scope-* / redact-thinking-* etc.). Channel-
	// specific → failover to a non-Bedrock sibling succeeds.
	"invalid beta flag",
	// Anthropic/GCP style beta rejection: "Unexpected value(s) ... for the
	// `anthropic-beta` header".
	"for the `anthropic-beta` header",
	// Bedrock 400 for opus operations it doesn't allow; failover to direct sibling.
	"Operation not allowed",
}

// IsUpstreamForcedRetryError returns true when the error message matches a
// known upstream stale-state signature. Used by shouldRetry to override
// ShouldSkipRetryAfterChannelAffinityFailure.
func IsUpstreamForcedRetryError(newApiErr *types.NewAPIError) bool {
	if newApiErr == nil {
		return false
	}
	msg := newApiErr.Error()
	for _, s := range upstreamForcedRetrySignatures {
		if strings.Contains(msg, s) {
			return true
		}
	}
	return false
}

func ResetStatusCode(newApiErr *types.NewAPIError, statusCodeMappingStr string) {
	if newApiErr == nil {
		return
	}
	if statusCodeMappingStr == "" || statusCodeMappingStr == "{}" {
		return
	}
	statusCodeMapping := make(map[string]any)
	err := common.Unmarshal([]byte(statusCodeMappingStr), &statusCodeMapping)
	if err != nil {
		return
	}
	if newApiErr.StatusCode == http.StatusOK {
		return
	}
	codeStr := strconv.Itoa(newApiErr.StatusCode)
	if value, ok := statusCodeMapping[codeStr]; ok {
		intCode, ok := parseStatusCodeMappingValue(value)
		if !ok {
			return
		}
		newApiErr.StatusCode = intCode
	}
}

func parseStatusCodeMappingValue(value any) (int, bool) {
	switch v := value.(type) {
	case string:
		if v == "" {
			return 0, false
		}
		statusCode, err := strconv.Atoi(v)
		if err != nil {
			return 0, false
		}
		return statusCode, true
	case float64:
		if v != math.Trunc(v) {
			return 0, false
		}
		return int(v), true
	case int:
		return v, true
	case json.Number:
		statusCode, err := strconv.Atoi(v.String())
		if err != nil {
			return 0, false
		}
		return statusCode, true
	default:
		return 0, false
	}
}

func TaskErrorWrapperLocal(err error, code string, statusCode int) *dto.TaskError {
	openaiErr := TaskErrorWrapper(err, code, statusCode)
	openaiErr.LocalError = true
	return openaiErr
}

func TaskErrorWrapper(err error, code string, statusCode int) *dto.TaskError {
	text := err.Error()
	lowerText := strings.ToLower(text)
	if strings.Contains(lowerText, "post") || strings.Contains(lowerText, "dial") || strings.Contains(lowerText, "http") {
		common.SysLog(fmt.Sprintf("error: %s", text))
		//text = "请求上游地址失败"
		text = common.MaskSensitiveInfo(text)
	}
	//避免暴露内部错误
	taskError := &dto.TaskError{
		Code:       code,
		Message:    text,
		StatusCode: statusCode,
		Error:      err,
	}

	return taskError
}

// TaskErrorFromAPIError 将 PreConsumeBilling 返回的 NewAPIError 转换为 TaskError。
func TaskErrorFromAPIError(apiErr *types.NewAPIError) *dto.TaskError {
	if apiErr == nil {
		return nil
	}
	return &dto.TaskError{
		Code:       string(apiErr.GetErrorCode()),
		Message:    apiErr.Err.Error(),
		StatusCode: apiErr.StatusCode,
		Error:      apiErr.Err,
	}
}
