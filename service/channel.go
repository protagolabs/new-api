func formatNotifyType(channelId int, status int) string {
	return fmt.Sprintf("%s_%d_%d", dto.NotifyTypeChannelUpdate, channelId, status)
}

// auditChannelStatus records an automatic enable/disable to the log table.
//
// Without this, a channel that is disabled and re-enabled between two glances
// at the admin page leaves no trace at all: requests fail with "no available
// channel", nothing is written to logs, and the channel looks healthy by the
// time anyone investigates. That is exactly what happened on 2026-08-16 with
// the MiniMax channels -- five hours of customer failures and no record of why.
//
// LogTypeSystem keeps these out of the per-user consumption views while leaving
// them queryable alongside everything else on the timeline.
func auditChannelStatus(channelId int, channelName string, status int, reason string) {
	action := "启用"
	if status == common.ChannelStatusAutoDisabled {
		action = "自动禁用"
	}
	content := fmt.Sprintf("渠道 #%d「%s」%s", channelId, channelName, action)
	if reason != "" {
		content = fmt.Sprintf("%s，原因：%s", content, common.LocalLogPreview(reason))
	}
	model.RecordLog(0, model.LogTypeSystem, content)
}

// disable & notify
func DisableChannel(channelError types.ChannelError, reason string) {
	common.SysLog(fmt.Sprintf("通道「%s」（#%d）发生错误，准备禁用，原因：%s", channelError.ChannelName, channelError.ChannelId, common.LocalLogPreview(reason)))

	// 检查是否启用自动禁用功能
	if !channelError.AutoBan {
		common.SysLog(fmt.Sprintf("通道「%s」（#%d）未启用自动禁用功能，跳过禁用操作", channelError.ChannelName, channelError.ChannelId))
		return
	}

	success := model.UpdateChannelStatus(channelError.ChannelId, channelError.UsingKey, common.ChannelStatusAutoDisabled, reason)
	if success {
		auditChannelStatus(channelError.ChannelId, channelError.ChannelName, common.ChannelStatusAutoDisabled, reason)
		subject := fmt.Sprintf("通道「%s」（#%d）已被禁用", channelError.ChannelName, channelError.ChannelId)
		content := fmt.Sprintf("通道「%s」（#%d）已被禁用，原因：%s", channelError.ChannelName, channelError.ChannelId, reason)
		NotifyRootUser(formatNotifyType(channelError.ChannelId, common.ChannelStatusAutoDisabled), subject, content)
	}
}

func EnableChannel(channelId int, usingKey string, channelName string) {
	success := model.UpdateChannelStatus(channelId, usingKey, common.ChannelStatusEnabled, "")
	if success {
		auditChannelStatus(channelId, channelName, common.ChannelStatusEnabled, "")
		subject := fmt.Sprintf("通道「%s」（#%d）已被启用", channelName, channelId)
		content := fmt.Sprintf("通道「%s」（#%d）已被启用", channelName, channelId)
		NotifyRootUser(formatNotifyType(channelId, common.ChannelStatusEnabled), subject, content)
	}
}

func ShouldDisableChannel(err *types.NewAPIError) bool {
	if !common.AutomaticDisableChannelEnabled {
		return false
	}
	if err == nil {
		return false
	}
	if types.IsChannelError(err) {
		return true
	}
	if types.IsSkipRetryError(err) {
		return false
	}
	if operation_setting.ShouldDisableByStatusCode(err.StatusCode) {
		return true
	}

	lowerMessage := strings.ToLower(err.Error())
	search, _ := AcSearch(lowerMessage, operation_setting.AutomaticDisableKeywords, true)
	return search
}

func ShouldEnableChannel(newAPIError *types.NewAPIError, status int) bool {
	if !common.AutomaticEnableChannelEnabled {
		return false
	}
	if newAPIError != nil {
		return false
	}
	if status != common.ChannelStatusAutoDisabled {
		return false
	}
	return true
}
